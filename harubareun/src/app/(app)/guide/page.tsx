function buildShareText(): string {
  const lines: string[] = ["[하루바른·나아 플랫폼 사용법]", ""];
  for (const s of SECTIONS) {
    lines.push(`${s.icon} ${s.title}`);
    for (const step of s.steps) lines.push(`- ${step}`);
    lines.push("");
  }
  lines.push("※ 좌하단 ‘📲 앱 설치’로 홈 화면에 앱처럼 추가할 수 있어요.");
  return lines.join("\n");
}

